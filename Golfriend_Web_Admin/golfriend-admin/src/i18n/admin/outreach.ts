/**
 * Every stable error code the callables may return. Kept in lockstep with
 * OUTREACH_ERROR_CODES in functions/src/outreachAuthority.ts by the localization verifier,
 * which fails in BOTH directions — a new server code with no translation, and a stale
 * translation for a code the server no longer emits.
 */
export const OUTREACH_ERROR_CODES: readonly string[] = Object.freeze([
  'unauthenticated', 'app_check_required', 'not_admin', 'insufficient_role',
  'payload_rejected', 'content_rejected', 'draft_not_found', 'duplicate_draft',
  'version_required', 'stale_write', 'invalid_state', 'separation_of_duties',
  'reviewer_not_assigned', 'digest_mismatch', 'draft_expired', 'draft_terminal',
  'jurisdiction_not_approved', 'legal_hold_unknown', 'legal_hold_active',
  'replay_payload_mismatch', 'retention_policy_unavailable', 'transmission_not_permitted',
  'internal_error',
]);

/**
 * Map a server error code to a dictionary key. An UNRECOGNIZED code maps to `err.unknown`,
 * which says nothing was changed — never to a blank string and never to the raw code. A
 * blank would render as an empty cell and read as success.
 */
export function outreachErrorKey(code: unknown): OutreachKey {
  if (typeof code !== 'string' || OUTREACH_ERROR_CODES.indexOf(code) === -1) return 'err.unknown';
  return `err.${code}` as OutreachKey;
}
