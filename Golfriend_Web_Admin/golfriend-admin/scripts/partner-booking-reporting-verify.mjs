import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), "utf8");
const domain = read("functions/src/bookingReportingDomain.ts");
const runtime = read("functions/src/bookingReportingRuntime.ts");
const ui = read("src/components/B2B/BookingOperationsReportV2.tsx");
const app = read("src/App.tsx");
const small = read("src/components/B2B/SmallBusinessDashboard.tsx");
const enterprise = read("src/components/B2B/EnterpriseDashboard.tsx");
const rules = read("partner-onboarding.firestore.rules");
let count = 0;
const ok = (name, condition) => { assert(condition, name); count++; console.log(`PASS ${name}`); };
ok("versioned schema", domain.includes("golfriend.booking-operations-report.v1"));
for (const code of ["OVER_CAPACITY", "ORPHANED_BOOKING", "STALE_ALTERNATIVE", "DUPLICATE_RECEIPT", "MISSING_COURSE_CLAIM", "STATUS_DIVERGENCE"]) ok(code, domain.includes(code));
ok("deterministic filtering and pagination", /normalizeFilters/.test(domain) && /nextCursor/.test(domain));
ok("timezone retained", /timeZone/.test(domain));
ok("privacy safe projection", /safeRows/.test(domain));
ok("financial export excluded", !/payment|fee|wallet|ledger|settlement/.test(domain.match(/privacySafeExport[\s\S]+$/)?.[0] || ""));
for (const name of ["getBookingOperationsPortalV2", "getBookingOperationsAdminV2", "reconcileBookingOperationsV2", "exportBookingOperationsV2", "getBookingOperationsReceiptV2"]) ok(`callable ${name}`, runtime.includes(`export const ${name}=onCall({enforceAppCheck:true}`));
ok("delegated membership authority", runtime.includes("partner_memberships") && runtime.includes("primary_owner") && runtime.includes("manager") && runtime.includes('c.role==="course_staff"?c.courseIds:[]'));
ok("admin global authority", runtime.includes("isActiveStaff"));
ok("expected source version", runtime.includes("SOURCE_VERSION_CONFLICT"));
ok("idempotent immutable receipts", runtime.includes("reconciliationReceiptId") && runtime.includes("immutable:true"));
ok("audit before export response", runtime.indexOf("await ref.create") < runtime.indexOf("privacySafeExport(report,format)"));
ok("deny all receipt rules", ["booking_reconciliation_receipts", "booking_report_export_receipts", "booking_report_access_audits"].every((x) => rules.includes(x)));
ok("all eight locales", ["th:", "ko:", "ja:", "zh:", "es:", "fr:", "de:"].every((x) => ui.includes(x)));
ok("localized filter label set", /all:\"/.test(ui) && /statusMap/.test(ui) && /retry:\"/.test(ui));
ok("localized table headers", ui.includes("copy.table.organization") && ui.includes("copy.table.course") && ui.includes("copy.table.timeZone") && ui.includes("copy.table.capacity"));
ok("localized status rendering", /getStatusLabel/.test(ui) && /STATUS_OPTIONS/.test(ui));
ok("accessible labels", ui.includes("aria-label={copy.retry}") && ui.includes("aria-label={copy.csv}") && ui.includes("aria-label={copy.reconcile}") && ui.includes("aria-label={copy.lookup}"));
ok("loading/empty/error retries localized", ui.includes('role="status"') && ui.includes('role="alert"') && ui.includes("copy.loading") && ui.includes("copy.empty") && ui.includes("copy.error") && ui.includes("copy.retry"));
ok("mounted admin", app.includes("<BookingOperationsReportV2 admin"));
ok("mounted small portal", small.includes("<BookingOperationsReportV2"));
ok("mounted enterprise portal", enterprise.includes("<BookingOperationsReportV2"));
ok("real exports", ui.includes("new Blob") && ui.includes("a.download"));
ok("receipt lookup", ui.includes("getBookingOperationsReceiptV2"));
console.log(`${count}/${count} Portal/Admin booking reporting verification PASS`);
